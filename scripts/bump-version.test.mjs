import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  chmodSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const scriptSource = join(repoRoot, 'scripts/bump-version.sh');
const fixtures = [];

function sh(cwd, args, env = {}) {
  const result = spawnSync(args[0], args.slice(1), {
    cwd,
    encoding: 'utf8',
    env: { ...process.env, ...env },
  });
  if (result.status !== 0) {
    throw new Error(
      `${args.join(' ')} failed (${result.status}): ${result.stderr || result.stdout}`,
    );
  }
  return result;
}

function makeFixture() {
  const root = mkdtempSync(join(tmpdir(), 'bump-version-'));
  fixtures.push(root);
  mkdirSync(join(root, 'scripts'));
  mkdirSync(join(root, 'src-tauri'));
  mkdirSync(join(root, '.github/workflows'), { recursive: true });
  mkdirSync(join(root, 'bin'));

  writeFileSync(
    join(root, 'package.json'),
    `${JSON.stringify({ name: 'pacto', version: '0.8.0' }, null, 2)}\n`,
  );
  writeFileSync(
    join(root, 'src-tauri/tauri.conf.json'),
    `${JSON.stringify({ version: '0.8.0' }, null, 2)}\n`,
  );
  writeFileSync(
    join(root, 'src-tauri/Cargo.toml'),
    '[package]\nname = "pacto"\nversion = "0.8.0"\nedition = "2021"\n\n[dependencies]\n',
  );
  writeFileSync(
    join(root, 'src-tauri/Cargo.lock'),
    `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "alloy"
version = "1.2.3"

[[package]]
name = "pacto"
version = "0.8.0"
dependencies = [
 "alloy",
]
`,
  );
  writeFileSync(
    join(root, 'pnpm-lock.yaml'),
    'lockfileVersion: "9.0"\n\nimporters:\n  .:\n    specifiers: {}\n',
  );
  writeFileSync(
    join(root, '.github/workflows/release.yaml'),
    'jobs:\n  publish:\n    steps:\n      - uses: tauri-apps/tauri-action@deadbeef\n',
  );
  writeFileSync(
    join(root, 'scripts/changelog.mjs'),
    `import { writeFileSync } from 'node:fs';
writeFileSync('CHANGELOG.md', '# Changelog\\n\\n## v0.1.0\\n\\n- Init project.\\n');
`,
  );
  writeFileSync(join(root, 'scripts/post-process-changelog.sh'), '#!/usr/bin/env bash\nexit 0\n');
  chmodSync(join(root, 'scripts/post-process-changelog.sh'), 0o755);

  const script = readFileSync(scriptSource, 'utf8');
  writeFileSync(join(root, 'scripts/bump-version.sh'), script, { mode: 0o755 });
  chmodSync(join(root, 'scripts/bump-version.sh'), 0o755);

  const log = join(root, 'invocations.log');
  writeFileSync(
    join(root, 'bin/pnpm'),
    `#!/usr/bin/env bash
echo "pnpm $*" >> "${log}"
exit 0
`,
  );
  writeFileSync(
    join(root, 'bin/cargo'),
    `#!/usr/bin/env bash
echo "cargo $*" >> "${log}"
exit 0
`,
  );
  chmodSync(join(root, 'bin/pnpm'), 0o755);
  chmodSync(join(root, 'bin/cargo'), 0o755);

  sh(root, ['git', 'init', '-q']);
  sh(root, ['git', 'config', 'user.email', 'bump-version-test@example.com']);
  sh(root, ['git', 'config', 'user.name', 'Bump Version Test']);
  sh(root, ['git', 'add', '.']);
  sh(root, ['git', 'commit', '-qm', 'init']);
  return { root, log };
}

function runBump(root, args) {
  return spawnSync('bash', [join(root, 'scripts/bump-version.sh'), ...args], {
    cwd: root,
    encoding: 'utf8',
    env: { ...process.env, PATH: `${join(root, 'bin')}:${process.env.PATH}` },
  });
}

function readJson(root, path) {
  return JSON.parse(readFileSync(join(root, path), 'utf8'));
}

function cargoTomlVersion(root) {
  const text = readFileSync(join(root, 'src-tauri/Cargo.toml'), 'utf8');
  return text.match(/^version = "([^"]+)"/m)?.[1];
}

function cargoLockVersion(root) {
  const text = readFileSync(join(root, 'src-tauri/Cargo.lock'), 'utf8');
  return text.match(/\[\[package\]\]\nname = "pacto"\nversion = "([^"]+)"/)?.[1];
}

function invocations(log) {
  try {
    return readFileSync(log, 'utf8').trim().split('\n').filter(Boolean);
  } catch {
    return [];
  }
}

after(() => {
  for (const root of fixtures) rmSync(root, { recursive: true, force: true });
});

describe('bump-version.sh', () => {
  it('rejects unknown flags', () => {
    const { root } = makeFixture();
    const result = runBump(root, ['patch', '--fast']);
    assert.equal(result.status, 1);
    assert.match(result.stdout + result.stderr, /unknown option --fast/);
  });

  it('skip-checks updates versions and Cargo.lock without compile or test tools', () => {
    const { root, log } = makeFixture();
    const result = runBump(root, ['patch', '--no-commit', '--skip-checks']);
    assert.equal(result.status, 0, result.stderr || result.stdout);
    assert.equal(readJson(root, 'package.json').version, '0.8.1');
    assert.equal(readJson(root, 'src-tauri/tauri.conf.json').version, '0.8.1');
    assert.equal(cargoTomlVersion(root), '0.8.1');
    assert.equal(cargoLockVersion(root), '0.8.1');
    assert.match(readFileSync(join(root, 'src-tauri/Cargo.lock'), 'utf8'), /name = "alloy"\nversion = "1\.2\.3"/);
    const calls = invocations(log);
    assert.deepEqual(calls, ['pnpm install --lockfile-only --ignore-scripts']);
    const staged = sh(root, ['git', 'diff', '--cached', '--name-only']).stdout.trim().split('\n');
    for (const path of [
      'CHANGELOG.md',
      'package.json',
      'src-tauri/Cargo.lock',
      'src-tauri/Cargo.toml',
      'src-tauri/tauri.conf.json',
    ]) {
      assert.ok(staged.includes(path), `expected ${path} to be staged, got ${staged.join(',')}`);
    }
    assert.match(result.stdout, /Version 0\.8\.1 staged \(not committed\)\./);
    const head = sh(root, ['git', 'log', '-1', '--format=%s']).stdout.trim();
    assert.equal(head, 'init');
  });

  it('accepts --skip-checks before the bump argument', () => {
    const { root, log } = makeFixture();
    const result = runBump(root, ['--skip-checks', '--no-commit', 'minor']);
    assert.equal(result.status, 0, result.stderr || result.stdout);
    assert.equal(readJson(root, 'package.json').version, '0.9.0');
    assert.deepEqual(invocations(log), ['pnpm install --lockfile-only --ignore-scripts']);
  });

  it('default path still runs frontend and Rust checks', () => {
    const { root, log } = makeFixture();
    const result = runBump(root, ['0.8.1-beta.1', '--no-commit']);
    assert.equal(result.status, 0, result.stderr || result.stdout);
    assert.equal(readJson(root, 'package.json').version, '0.8.1-beta.1');
    assert.equal(cargoLockVersion(root), '0.8.1-beta.1');
    assert.deepEqual(invocations(log), [
      'pnpm install',
      'pnpm check',
      'pnpm test',
      'cargo check',
      'cargo test',
    ]);
  });

  it('refuses to bump when the release tag already exists', () => {
    const { root } = makeFixture();
    sh(root, ['git', 'tag', 'v0.8.1']);
    const result = runBump(root, ['patch', '--skip-checks', '--no-commit']);
    assert.equal(result.status, 1);
    assert.match(result.stdout + result.stderr, /tag v0\.8\.1 already exists/);
    assert.equal(readJson(root, 'package.json').version, '0.8.0');
  });
});
